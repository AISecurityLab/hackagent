"""Refresh the HTTP API schema snapshot and the API reference pages built from it.

The API tab's reference (``docs/docs/api/reference/``) is generated by
``docusaurus-plugin-openapi-docs`` from a committed snapshot of the HackAgent
API's OpenAPI schema, ``docs/static/openapi/hackagent-api.json`` (also served
as a download at ``/openapi/hackagent-api.json``). Both are committed, so the
docs build needs neither the API's source nor network access.

The API's source is in a separate, private repository, so CI cannot refresh
the snapshot. Run this script after an API change that the docs should show::

    # From a checkout of the API repository (preferred: it can be ahead of
    # production). Needs uv; run `uv sync --all-extras --frozen` there first.
    uv run python docs/scripts/update_api_schema.py --api-repo ../hackagent-api

    # Or from the schema production serves:
    uv run python docs/scripts/update_api_schema.py --url

    # Or from a schema file you already have:
    uv run python docs/scripts/update_api_schema.py --input openapi.json

Each writes the snapshot and regenerates the pages (``--no-pages`` skips
that); commit both. ``--check`` changes nothing: it fails when the snapshot
is not in the form this script writes or when the committed pages differ
from what the plugin generates from it. It needs ``npm ci`` in ``docs/``.

From an API checkout the schema is generated the way production serves it:
``manage.py spectacular`` with the test settings (which need no database or
secrets) and ``AUTH_PROVIDER=auth0``, the hosted service's login provider,
which names the login-token security scheme ``Auth0JWTAccessToken``. The
script refuses a schema with another login scheme (a ``.env.local`` in the
API checkout overrides the environment, so check it if that happens).

The snapshot is the API's schema with three presentation changes, nothing
else:

* the LLM gateway operations carry two tags, ``generate`` and ``openai``, so
  generated clients group them both ways. The reference lists them once,
  under ``generate``: the ``openai`` tag is dropped and its description is
  merged into ``generate``'s.
* each tag gets an ``x-displayName`` (the sidebar label), such as ``Agents``
  for ``agent``.
* a request body schema that has named examples gets the first one as its
  ``example``. The reference builds its default request body, and its curl
  and Python samples, from the schema's example; without one it fills in
  every optional field with placeholders and leaves out free-form JSON
  fields such as a campaign's ``spec``, so the samples would be refused.

It is written with sorted keys and two-space indentation so a schema change
shows as a small diff. Three kinds of object keep the API's order because the
reference shows it: ``paths`` (the order of the operations in the sidebar),
each path's methods, and each schema's ``properties`` (the order of fields).
"""

from __future__ import annotations

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[2]
DOCS_SITE = ROOT / "docs"
SNAPSHOT = DOCS_SITE / "static" / "openapi" / "hackagent-api.json"
PAGES = DOCS_SITE / "docs" / "api" / "reference"
PRODUCTION_SCHEMA_URL = "https://api.hackagent.dev/schema/?format=json"

#: The security scheme of production's login tokens (AUTH_PROVIDER=auth0).
PRODUCTION_LOGIN_SCHEME = "Auth0JWTAccessToken"

#: Tags that duplicate another tag: operations are listed under the second.
DUPLICATE_TAGS = {"openai": "generate"}

#: Sidebar labels of the API's tags. A tag missing here gets its name,
#: capitalised.
TAG_LABELS = {
    "agent": "Agents",
    "campaign": "Campaigns",
    "run": "Runs",
    "result": "Results",
    "attack": "Attack configurations",
    "secret": "Secrets",
    "generate": "LLM gateway",
    "key": "API keys",
    "apilogs": "Usage logs",
    "organization": "Organizations",
    "user": "Users",
    "credits": "Credits",
    "license": "License",
}

_SEE_OTHER_TAG = re.compile(r"\s*The same operations are listed under `\w+`\.")


def merge_duplicate_tags(schema: dict[str, Any]) -> None:
    tags = schema.get("tags", [])
    by_name = {tag["name"]: tag for tag in tags}
    for duplicate, primary in DUPLICATE_TAGS.items():
        for item in schema.get("paths", {}).values():
            for operation in item.values():
                if not isinstance(operation, dict) or "tags" not in operation:
                    continue
                names = [primary if t == duplicate else t for t in operation["tags"]]
                operation["tags"] = list(dict.fromkeys(names))
        if duplicate in by_name and primary in by_name:
            descriptions = [
                _SEE_OTHER_TAG.sub("", by_name[name].get("description", "")).strip()
                for name in (primary, duplicate)
            ]
            by_name[primary]["description"] = "\n\n".join(d for d in descriptions if d)
        tags = [tag for tag in tags if tag["name"] != duplicate]
    if tags:
        schema["tags"] = tags


def label_tags(schema: dict[str, Any]) -> None:
    for tag in schema.get("tags", []):
        tag.setdefault(
            "x-displayName", TAG_LABELS.get(tag["name"], tag["name"].capitalize())
        )


def example_request_bodies(schema: dict[str, Any]) -> None:
    """Give each request body schema the value of its first named example.

    A schema shared by several operations takes the first operation's
    example, in path order; a schema that has an ``example`` keeps it.
    """
    components = schema.get("components", {}).get("schemas", {})
    for item in schema.get("paths", {}).values():
        for operation in item.values():
            if not isinstance(operation, dict):
                continue
            content = operation.get("requestBody", {}).get("content", {})
            media = content.get("application/json", {})
            ref = media.get("schema", {}).get("$ref", "")
            examples = list((media.get("examples") or {}).values())
            component = components.get(ref.rsplit("/", 1)[-1]) if ref else None
            if component is not None and examples and "value" in examples[0]:
                component.setdefault("example", examples[0]["value"])


def transform(schema: dict[str, Any]) -> dict[str, Any]:
    """Apply the presentation changes described in the module docstring."""
    merge_duplicate_tags(schema)
    label_tags(schema)
    example_request_bodies(schema)
    return schema


def _sorted(value: Any, keep_order: bool = False) -> Any:
    """Sort object keys recursively, except in a ``properties`` object."""
    if isinstance(value, dict):
        keys = list(value) if keep_order else sorted(value)
        return {
            key: _sorted(value[key], keep_order=key == "properties") for key in keys
        }
    if isinstance(value, list):
        return [_sorted(item) for item in value]
    return value


def render(schema: dict[str, Any]) -> str:
    """The snapshot's text: stable key order, two-space indent, final newline."""
    ordered = _sorted(schema)
    # The paths and their methods keep the API's order: the sidebar's.
    ordered["paths"] = {
        path: {method: _sorted(operation) for method, operation in item.items()}
        for path, item in schema.get("paths", {}).items()
    }
    return json.dumps(ordered, indent=2, ensure_ascii=False) + "\n"


def schema_from_api_repo(api_repo: Path) -> dict[str, Any]:
    if not (api_repo / "manage.py").is_file():
        sys.exit(f"{api_repo} is not a checkout of the HackAgent API (no manage.py).")
    env = {
        **os.environ,
        "AUTH_PROVIDER": "auth0",
        "DJANGO_SETTINGS_MODULE": "src.config.settings_test",
    }
    env.pop("VIRTUAL_ENV", None)
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "schema.json"
        subprocess.run(
            [
                "uv",
                "run",
                "--frozen",
                "python",
                "manage.py",
                "spectacular",
                "--file",
                str(out),
                "--format",
                "openapi-json",
            ],
            cwd=api_repo,
            env=env,
            check=True,
            stdout=subprocess.DEVNULL,
        )
        return json.loads(out.read_text(encoding="utf-8"))


def schema_from_url(url: str) -> dict[str, Any]:
    with urllib.request.urlopen(url, timeout=60) as response:  # noqa: S310
        return json.load(response)


def check_login_scheme(schema: dict[str, Any]) -> None:
    schemes = schema.get("components", {}).get("securitySchemes", {})
    login = [name for name in schemes if name.endswith("JWTAccessToken")]
    if login != [PRODUCTION_LOGIN_SCHEME]:
        sys.exit(
            f"The schema's login scheme is {login}, not [{PRODUCTION_LOGIN_SCHEME!r}]: "
            "it was not generated with AUTH_PROVIDER=auth0, as production runs. "
            "A .env.local in the API checkout overrides the environment."
        )


def read_pages() -> dict[str, bytes]:
    if not PAGES.is_dir():
        return {}
    return {
        str(path.relative_to(PAGES)): path.read_bytes()
        for path in sorted(PAGES.rglob("*"))
        if path.is_file()
    }


def write_pages(pages: dict[str, bytes]) -> None:
    shutil.rmtree(PAGES, ignore_errors=True)
    for name, content in pages.items():
        path = PAGES / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)


def generate_pages() -> None:
    """Regenerate the reference from the snapshot, removing stale pages."""
    npm = shutil.which("npm")
    if npm is None:
        sys.exit("npm is needed to generate the API pages (run `npm ci` in docs/).")
    shutil.rmtree(PAGES, ignore_errors=True)
    subprocess.run(
        [
            npm,
            "run",
            "--silent",
            "docusaurus",
            "--",
            "gen-api-docs",
            "hackagent",
            "--plugin-id",
            "openapi",
        ],
        cwd=DOCS_SITE,
        check=True,
        stdout=subprocess.DEVNULL,
    )


def check() -> int:
    problems = []
    current = SNAPSHOT.read_text(encoding="utf-8")
    if render(transform(json.loads(current))) != current:
        problems.append(
            f"{SNAPSHOT.relative_to(ROOT)} is not in the form this script writes."
        )
    committed = read_pages()
    try:
        generate_pages()
        generated = read_pages()
    finally:
        write_pages(committed)
    changed = sorted(
        name
        for name in committed.keys() | generated.keys()
        if committed.get(name) != generated.get(name)
    )
    if changed:
        problems.append(
            f"{PAGES.relative_to(ROOT)} differs from the pages generated from the "
            f"snapshot ({len(changed)} files, such as {', '.join(changed[:5])})."
        )
    for problem in problems:
        print(f"❌ {problem}")
    if problems:
        print(
            "Run: uv run python docs/scripts/update_api_schema.py --input "
            f"{SNAPSHOT.relative_to(ROOT)}"
        )
        return 1
    print(
        f"✅ The API schema snapshot and its {len(committed)} reference files are up to date."
    )
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    source = parser.add_mutually_exclusive_group(required=True)
    source.add_argument("--api-repo", type=Path, help="generate from this API checkout")
    source.add_argument(
        "--url",
        nargs="?",
        const=PRODUCTION_SCHEMA_URL,
        help=f"fetch the schema (default {PRODUCTION_SCHEMA_URL})",
    )
    source.add_argument("--input", type=Path, help="read the schema from this file")
    source.add_argument(
        "--check",
        action="store_true",
        help="fail if the snapshot or the pages are stale; change nothing",
    )
    parser.add_argument(
        "--no-pages", action="store_true", help="write the snapshot only"
    )
    args = parser.parse_args()

    if args.check:
        return check()
    if args.api_repo:
        schema = schema_from_api_repo(args.api_repo.resolve())
    elif args.url:
        schema = schema_from_url(args.url)
    else:
        schema = json.loads(args.input.read_text(encoding="utf-8"))
    check_login_scheme(schema)
    SNAPSHOT.parent.mkdir(parents=True, exist_ok=True)
    SNAPSHOT.write_text(render(transform(schema)), encoding="utf-8")
    print(f"Wrote {SNAPSHOT.relative_to(ROOT)}")
    if not args.no_pages:
        generate_pages()
        print(f"Generated {len(read_pages())} files in {PAGES.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
