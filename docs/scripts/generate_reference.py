"""Generate the docs site's reference content from the code.

Every file this writes is derived from the code, so it cannot drift from it:

* ``cli/campaign-files/``: the campaign format — each field's type, default
  and description — from the Pydantic models in
  :mod:`hackagent.orchestrator.campaign.spec`, with the catalogs (dataset
  presets, judge scoring types, agent types) from their registries;
* ``cli/commands.md``: the command line, by walking the Click tree;
* ``attacks/<type>/_<name>.generated.mdx``: each attack's helper models,
  parameters and campaign snippet, from its parameter model. These are MDX
  partials the hand-written attack pages import; ``_list.generated.mdx`` per
  type and ``attacks/_catalog.generated.mdx`` list the attacks;
* ``static/schema/campaign.schema.json``, for editor autocompletion.

Run it after changing any of those::

    uv run python docs/scripts/generate_reference.py

``tests/unit/docs/test_generated_reference.py`` fails when what is committed
differs from what this produces, so the two cannot drift apart.
"""

from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "docs" / "scripts"))

from reference import attack_pages, cli_page, spec_pages  # noqa: E402
from reference.markup import page, table  # noqa: E402

DOCS = ROOT / "docs" / "docs"
CAMPAIGN_FILES = DOCS / "cli" / "campaign-files"
COMMANDS = DOCS / "cli" / "commands.md"
ATTACKS = DOCS / "attacks"
SCHEMA = ROOT / "docs" / "static" / "schema" / "campaign.schema.json"

