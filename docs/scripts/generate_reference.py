def _overview() -> str:
    """The campaign-files landing page, with a row per section."""
    rows = [
        [f"[{title}]({name}.md)", tagline]
        for name, (title, tagline) in spec_pages.TITLES.items()
    ]
    rows.append(["[Commands](../commands.md)", "Every `hackagent` command."])
    body = OVERVIEW.format(sections=table(["Section", "What it is for"], rows))
    return page(
        {
            "title": "Campaign files",
            "description": "Every field of the campaign format, generated from the code.",
            "sidebar_position": 1,
        },
        body,
    )


def _category(label: str, position: int, link: str) -> str:
    """A ``_category_.json``, which names a folder in an autogenerated sidebar."""
    data = {"label": label, "position": position, "link": {"type": "doc", "id": link}}
    return json.dumps(data, indent=2) + "\n"


def generate() -> dict[Path, str]:
    """Every generated file, as a path-to-content map."""
    from hackagent.orchestrator.campaign.spec import campaign_json_schema

    links = spec_pages.build_links()
    files: dict[Path, str] = {CAMPAIGN_FILES / "index.md": _overview()}
    for name, content in spec_pages.build_pages(links).items():
        files[CAMPAIGN_FILES / name] = content
    # The CLI sidebar is generated from the folder, so this one names it.
    files[CAMPAIGN_FILES / "_category_.json"] = _category(
        "Campaign files", 20, "cli/campaign-files/index"
    )
    files[COMMANDS] = cli_page.build_page()
    for name, content in attack_pages.build_partials(links).items():
        files[DOCS / name] = content
    files[SCHEMA] = json.dumps(campaign_json_schema(), indent=2) + "\n"
    return files


def owned() -> set[Path]:
    """Every file on disk that this script owns, generated or left over.

    The campaign-files folder is generated whole; under ``attacks/`` only the
    ``_*.generated.mdx`` partials are, the pages beside them are hand-written.
    """
    found = set(CAMPAIGN_FILES.rglob("*")) if CAMPAIGN_FILES.exists() else set()
    found |= set(ATTACKS.rglob("_*.generated.mdx"))
    return {path for path in found if path.is_file()}


def write(files: dict[Path, str]) -> list[Path]:
    """Write every file, removing generated files that are no longer produced."""
    if CAMPAIGN_FILES.exists():
        shutil.rmtree(CAMPAIGN_FILES)
    for path in owned():
        path.unlink()
    written = []
    for path, content in files.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        written.append(path)
    return written


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="Report whether the committed files are up to date, write nothing.",
    )
    args = parser.parse_args()
    files = generate()

    if args.check:
        stale = [
            path
            for path, content in files.items()
            if not path.is_file() or path.read_text(encoding="utf-8") != content
        ]
        leftover = sorted(owned() - set(files))
        for path in stale:
            print(f"out of date: {path.relative_to(ROOT)}")
        for path in leftover:
            print(f"no longer generated: {path.relative_to(ROOT)}")
        if stale or leftover:
            print("\nRun: uv run python docs/scripts/generate_reference.py")
            return 1
        print(f"{len(files)} generated files are up to date")
        return 0

    written = write(files)
    print(f"Wrote {len(written)} generated files under {DOCS.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
